return {
  {
    "lervag/vimtex",
    lazy = false,
    init = function()
      vim.g.vimtex_view_method = "zathura"
      vim.g.vimtex_compiler_method = "latexmk"
      vim.g.vimtex_compiler_latexmk = {
        callback = 1,
        continuous = 1,
        executable = "latexmk",
        aux_dir = ".latex-aux", -- keep .aux/.log/.fls/etc. out of sight; only the pdf lands next to the .tex
        options = {
          "-pdf",
          "-shell-escape",
          "-verbose",
          "-file-line-error",
          "-synctex=1",
          "-interaction=nonstopmode",
        },
      }
      vim.g.vimtex_imaps_enabled = 0
      vim.g.vimtex_quickfix_open_on_warning = 0
    end,
  },
}
